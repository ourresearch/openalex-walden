def missing(v: Any) -> bool:
    if v is None:
        return True
    try:
        return bool(pd.isna(v))
    except (TypeError, ValueError):
        return False


def txt(v: Any, limit: int | None = None, squash: bool = False) -> str | None:
    if missing(v):
        return None
    s = str(v)
    s = " ".join(s.split()) if squash else s.strip()
    if limit is not None:
        s = s[:limit].rstrip()
    return s or None


def to_int(v: Any) -> int | None:
    if missing(v) or v == "":
        return None
    try:
        return int(float(v))
    except (TypeError, ValueError):
        return None


def to_bool(v: Any) -> bool | None:
    if missing(v):
        return None
    if isinstance(v, str):
        return {"true": True, "false": False}.get(v.strip().lower())
    return bool(v)


def as_json(v: Any) -> Any:
    if isinstance(v, (list, dict)):
        return v
    if missing(v):
        return None
    if isinstance(v, str):
        v = v.strip()
        return json.loads(v) if v else None
    return v


def page_count(first: Any, last: Any) -> int | None:
    f, l = txt(first), txt(last)
    if f and l and f.isdigit() and l.isdigit():
        n = int(l) - int(f) + 1
        return n if 0 < n <= 5000 else None
    return None


def norm_title(s: str | None) -> str:
    return re.sub(r"[\W_]+", "", (s or "").lower())


_ATTR = re.compile(r"""([a-zA-Z_:.\-]+)\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s"'>]+))""")


_DROP = re.compile(r"author|date|pdf|html_url|fulltext|image|video|audio|mime|keyword|description|abstract|reference|"
                   r"viewport|robots|verification|generator|csrf|twitter|^fb:|language|doi|issn|url|rights|license|"
                   r"citation_volume|citation_issue|theme|msapplication|format-detection|referrer|content-type")


_TIER0 = re.compile(r"(^|[._:\-])(type|types|genre|articletype|article[_-]type|contenttype|content[_-]type|doctype|"
                    r"document[_-]?type|pubtype|publicationtype|section|category)($|[._:\-])")


_TIER1 = re.compile(r"journal_title|conference|inbook|book_title|series_title|dissertation|thesis|technical_report|"
                    r"isbn|publisher|ispartof|publicationname|firstpage|lastpage|pagerange|ispublished|event_title|"
                    r"institution|department|degree|site_name|format\.extent|dc\.source|num_pages|_pages$|"
                    r"proceedings|endpage|startpage|arxiv_id|editor")


_TIER2 = re.compile(r"(^|[._:])title$")


_TIER_CAPS = (6, 6, 2)


def parse_tag(raw: str) -> tuple[str, str] | None:
    attrs: dict[str, str] = {}
    for m in _ATTR.finditer(raw):
        val = next(g for g in (m.group(2), m.group(3), m.group(4)) if g is not None)
        attrs.setdefault(m.group(1).lower(), val)
    key = attrs.get("name") or attrs.get("property") or attrs.get("itemprop") or attrs.get("http-equiv")
    content = attrs.get("content")
    if not key or content is None:
        return None
    key = html.unescape(key).strip().lower()
    key = key[len("bepress_"):] if key.startswith("bepress_") else key
    content = " ".join(html.unescape(content).split())
    return (key, content) if key and content else None


def select_tags(tx_meta: Any) -> tuple[list[str] | None, int | None]:
    tags = as_json(tx_meta)
    if tags is None:
        return None, None
    if not isinstance(tags, list):
        tags = [tags]
    tiers: list[list[str]] = [[], [], []]
    seen, per_key = set(), {}
    for raw in tags:
        parsed = parse_tag(str(raw)) if raw is not None else None
        if not parsed:
            continue
        key, content = parsed
        if _DROP.search(key) and "conference" not in key:
            continue
        tier = 0 if _TIER0.search(key) else 1 if _TIER1.search(key) else 2 if _TIER2.search(key) else None
        if tier is None:
            continue
        item = f"{key}={content[:200].rstrip()}"
        if item.lower() in seen or per_key.get(key, 0) >= 3 or len(tiers[tier]) >= _TIER_CAPS[tier]:
            continue
        seen.add(item.lower())
        per_key[key] = per_key.get(key, 0) + 1
        tiers[tier].append(item)
    return tiers[0] + tiers[1] + tiers[2], len(tags)


def relations(ids: Any) -> list[str] | None:
    items = as_json(ids)
    if not items:
        return None
    out = []
    for d in items if isinstance(items, list) else []:
        rel = (d or {}).get("relationship")
        if not rel or rel in ("self", "References", "Cites", "IsCitedBy", "IsReferencedBy"):
            continue
        s = f"{rel}:{d.get('namespace')}:{d.get('id')}"[:120]
        if s not in out:
            out.append(s)
    return out[:6] or None


def shape(w: dict, recs: list[dict]) -> dict:
    """Raw row (from SQL or the local export) -> blinded pack. The only place pack fields are created."""
    title = txt(w.get("title"), 500)
    bib = as_json(w.get("biblio")) or {}
    biblio = {"volume": txt(bib.get("volume"), 20), "issue": txt(bib.get("issue"), 20),
              "first_page": txt(bib.get("first_page"), 20), "last_page": txt(bib.get("last_page"), 20),
              "page_count": page_count(bib.get("first_page"), bib.get("last_page"))}
    ids = as_json(w.get("ids")) or {}
    idx = as_json(w.get("indexed_in")) or []
    rows, seen = [], set()
    for r in sorted(recs, key=lambda r: (to_int(r.get("pos")) if to_int(r.get("pos")) is not None else 10**6,
                                         str(r.get("provenance")), str(r.get("native_id")))):
        k = (r.get("provenance"), r.get("native_id"))
        if k in seen:
            continue
        seen.add(k)
        prov = txt(r.get("provenance"))
        rtitle = txt(r.get("title"), 300)
        tags, n_tags = select_tags(r.get("tx_meta"))
        rows.append({
            "provenance": prov,
            "native_id": txt(r.get("native_id"), 150),
            "raw_type": None if prov == "pubmed" else txt(r.get("raw_type"), 120),
            "crossref_subtype": txt(r.get("cr_subtype"), 40),
            "source_name": txt(r.get("source_name"), 200),
            "source_type": txt(r.get("src_type"), 40),
            "publisher": txt(r.get("publisher"), 120),
            "version": txt(r.get("version"), 40),
            "title": rtitle if rtitle and norm_title(rtitle) != norm_title(title) else None,
            "published_date": txt(r.get("published_date"), 10),
            "volume": txt(r.get("volume"), 20), "issue": txt(r.get("issue"), 20),
            "first_page": txt(r.get("first_page"), 20), "last_page": txt(r.get("last_page"), 20),
            "page_count": page_count(r.get("first_page"), r.get("last_page")),
            "reference_count": to_int(r.get("n_references")),
            "landing_page_url": txt(r.get("landing_page_url"), 250),
            "relations": relations(r.get("ids")),
            "page_title": txt(r.get("tx_page_title"), 200),
            "page_tags": tags,
            "page_tags_total": n_tags,
        })
    signals = {
        "doi": txt(re.sub(r"^https?://(dx\.)?doi\.org/", "", str(w.get("doi") or ""), flags=re.I)),
        "title": title,
        "publication_year": to_int(w.get("publication_year")),
        "language": txt(w.get("language"), 10),
        "publisher": txt(w.get("publisher"), 120),
        "authors_count": to_int(w.get("authors_count")),
        "referenced_works_count": to_int(w.get("referenced_works_count")),
        "abstract": txt(w.get("abstract"), 1500, squash=True),
        "fulltext_excerpt": txt(w.get("fulltext_head"), 1000, squash=True),
        "biblio": biblio if any(v is not None for v in biblio.values()) else None,
        "identifiers": sorted(k for k, v in (ids.items() if isinstance(ids, dict) else []) if v and k != "openalex") or None,
        "indexed_in": sorted(str(x) for x in idx) if isinstance(idx, list) and idx else None,
        "is_retracted": to_bool(w.get("is_retracted")),
        "records_total": len(rows),
        "records": rows[:MAX_RECORDS],
    }
    return {"work_id": int(to_int(w["work_id"])), "pack_version": PACK_VERSION, "signals": signals}


def gate(path: Path, expected_ids: set[int]) -> list[dict]:
    """BLINDING GATE: re-read the file; every key must be whitelisted; PubMed raw types must be null."""
    packs = [json.loads(x) for x in path.read_text(encoding="utf-8").split("\n") if x.strip()]  # not splitlines(): U+2028/2029/0085
    ids = [p["work_id"] for p in packs]
    if len(ids) != len(set(ids)) or set(ids) != expected_ids:
        raise SystemExit(f"GATE FAIL {path.name}: {len(ids)} packs, {len(set(ids))} unique, expected {len(expected_ids)}")
    for p in packs:
        if list(p) != ["work_id", "pack_version", "signals"]:
            raise SystemExit(f"GATE FAIL {path.name} W{p.get('work_id')}: top-level keys {list(p)}")
        s = p["signals"]
        if list(s) != SIGNAL_KEYS:
            raise SystemExit(f"GATE FAIL {path.name} W{p['work_id']}: signal keys {list(s)}")
        if s["biblio"] is not None and list(s["biblio"]) != BIBLIO_KEYS:
            raise SystemExit(f"GATE FAIL {path.name} W{p['work_id']}: biblio keys")
        for r in s["records"]:
            if list(r) != RECORD_KEYS:
                raise SystemExit(f"GATE FAIL {path.name} W{p['work_id']}: record keys {list(r)}")
            if r["provenance"] == "pubmed" and r["raw_type"] is not None:
                raise SystemExit(f"GATE FAIL {path.name} W{p['work_id']}: PubMed publication type leaked")
            for k in ("page_tags", "relations"):
                if r[k] is not None and not all(isinstance(x, str) for x in r[k]):
                    raise SystemExit(f"GATE FAIL {path.name} W{p['work_id']}: {k} not strings")
    print(f"BLINDING GATE OK {path.name}: {len(packs)} packs, keys whitelisted, PubMed raw types null")
    return packs
