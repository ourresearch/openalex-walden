MAX_CHARS = {"abstract": 1200, "fulltext": 300, "title": 300, "page_title": 160, "tags": 6, "records": 6}


def _v(x) -> str:
    return "" if x is None else str(x)


RENDER_VERSION_V3 = "s2r3"


RENDER_VERSION_V3_NOMED = "s2r3nm"


MAX_MEDLINE = 8


def _txt(x) -> str | None:
    if x is None:
        return None
    s = str(x).strip()
    return s or None


def page_count(first, last) -> int | None:
    """devproof/build_packs.py page_count(), but isdecimal: isdigit passes '⑥' or '²', which int() refuses (#1976,
    11 Nov: a circled page number killed backfill chunk 9). Every value int() accepted before gives the same count."""
    f, l = _txt(first), _txt(last)
    if f and l and f.isdecimal() and l.isdecimal():
        n = int(l) - int(f) + 1
        return n if 0 < n <= 5000 else None
    return None


def _to_int(v) -> int | None:
    try:
        if v is None or (isinstance(v, float) and v != v) or v == "":
            return None
        return int(float(v))
    except (TypeError, ValueError):
        return None


def key(prov, nid) -> tuple[str, str]:
    p = str(prov or "")
    n = str(nid or "")
    return (p, n.lower() if p in ("crossref", "datacite") else n)


def enrich(pack: dict, bmap: dict) -> dict:
    """Copy of the pack with B fields on its records (fill-only for pages/refs)."""
    if not bmap:
        return pack
    p = copy.deepcopy(pack)
    for r in p["signals"].get("records") or []:
        b = bmap.get(key(r.get("provenance"), r.get("native_id")))
        if not b:
            continue
        if r.get("page_count") in (None, "") and ("first_page" in b or "last_page" in b):
            r["page_count"] = page_count(b.get("first_page"), b.get("last_page"))
        if r.get("reference_count") in (None, "") and b.get("n_references") is not None:
            r["reference_count"] = _to_int(b.get("n_references"))
        if b.get("medline_types"):
            r["medline_types"] = b["medline_types"]
        for k in ("dc_type_general", "dc_resource_type"):
            if b.get(k):
                r[k] = b[k]
    return p


def render_v3(pack: dict, bmap: dict | None = None, medline: bool = True) -> str:
    """s2r2's text (stage2/common.py render, same order and truncation) + the B lines. Deterministic.
    medline=False drops the "MEDLINE types" line (worktype-lead 11-03: a final-only ablation, so v3 has a variant that
    stays independent of MEDLINE); its texts hash under RENDER_VERSION_V3_NOMED."""
    s = enrich(pack, bmap or {})["signals"]
    b = s.get("biblio") or {}
    L = [f"Title: {(_v(s.get('title')) or '(none)')[:MAX_CHARS['title']]}"]
    meta = [f"Year: {_v(s.get('publication_year')) or '?'}", f"Authors: {_v(s.get('authors_count')) or '?'}",
            f"References: {_v(s.get('referenced_works_count')) or '0'}"]
    if b.get("page_count") or b.get("first_page"):
        meta.append(f"Pages: {_v(b.get('page_count')) or '?'} ({_v(b.get('first_page'))}-{_v(b.get('last_page'))})")
    if s.get("is_retracted"):
        meta.append("Retracted: yes")
    L.append(" | ".join(meta))
    ids = [f"DOI: {s['doi']}"] if s.get("doi") else ["DOI: none"]
    if s.get("indexed_in"):
        ids.append("Indexed in: " + ", ".join(s["indexed_in"]))
    if s.get("identifiers"):
        ids.append("Ids: " + ", ".join(s["identifiers"]))
    L.append(" | ".join(ids))
    recs = s.get("records") or []
    for i, r in enumerate(recs[:MAX_CHARS["records"]], 1):
        parts = [f"Record {i}: {_v(r.get('provenance'))}"]
        if r.get("raw_type"):
            parts[0] += f" type \"{r['raw_type']}\""
        if r.get("crossref_subtype"):
            parts.append(f"subtype {r['crossref_subtype']}")
        if r.get("source_type") or r.get("source_name"):
            parts.append(f"source {_v(r.get('source_type')) or '?'} \"{_v(r.get('source_name'))[:120]}\"")
        for k, lab in (("version", ""), ("page_count", "pages "), ("reference_count", "refs ")):
            if r.get(k) not in (None, ""):
                parts.append(f"{lab}{r[k]}")
        if r.get("relations"):
            parts.append("relations " + ", ".join(x.split(":", 1)[0] for x in r["relations"]))
        L.append(" | ".join(parts))
        # ---- v3 additions (only when B has them)
        if medline and r.get("medline_types"):
            L.append("  MEDLINE types: " + "; ".join(t[:60] for t in r["medline_types"][:MAX_MEDLINE]))
        if r.get("dc_type_general") or r.get("dc_resource_type"):
            L.append("  DataCite type: " + " / ".join(x for x in (r.get("dc_type_general"), r.get("dc_resource_type")) if x))
        if r.get("title"):
            L.append(f"  record title: {r['title'][:160]}")
        if r.get("page_title"):
            L.append(f"  page title: {r['page_title'][:MAX_CHARS['page_title']]}")
        if r.get("page_tags"):
            L.append("  page tags: " + "; ".join(t[:80] for t in r["page_tags"][:MAX_CHARS["tags"]]))
    if s.get("records_total", 0) > len(recs[:MAX_CHARS["records"]]):
        L.append(f"(+{s['records_total'] - len(recs[:MAX_CHARS['records']])} more records)")
    if s.get("abstract"):
        L.append(f"Abstract: {s['abstract'][:MAX_CHARS['abstract']]}")
    return "\n".join(L)


def text_hash_v3(text: str, medline: bool = True) -> str:
    v = RENDER_VERSION_V3 if medline else RENDER_VERSION_V3_NOMED
    return hashlib.sha256(f"{v}\n{text}".encode()).hexdigest()[:32]
