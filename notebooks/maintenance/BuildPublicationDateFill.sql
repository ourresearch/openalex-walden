CREATE OR REPLACE TABLE openalex.works.publication_date_fill AS
WITH targets AS (
  SELECT id AS work_id, locations, primary_location.source.id AS src_id, primary_location.endpoint_id AS src_ep, doi
  FROM openalex.works.openalex_works
  WHERE publication_year IS NULL OR publication_year >= 10000
),
repo_locs AS (
  SELECT t.work_id, l.native_id AS nid, l.endpoint_id AS ep
  FROM targets t LATERAL VIEW explode(t.locations) x AS l WHERE l.provenance = 'repo'
),
-- the two copies of a repository record: the backfill-era XML and the live harvest; the live copy wins on an equal or
-- newer datestamp, as in repo_works' _sequence
b AS (
  SELECT pmh_id AS nid, endpoint_id AS ep, regexp_extract_all(api_raw, '<dc:date[^>]*>(.*?)</dc:date>', 1) AS dates,
         regexp_extract(api_raw, '<datestamp>(.*?)</datestamp>', 1) AS ds
  FROM openalex.repo.repo_items_backfill WHERE pmh_id IN (SELECT nid FROM repo_locs)
),
lv AS (
  SELECT `ns0:header`.`ns0:identifier` AS nid, max_by(`ns0:metadata`.`ns1:dc`.`dc:date`, `ns0:header`.`ns0:datestamp`) AS dates,
         max(`ns0:header`.`ns0:datestamp`) AS ds
  FROM openalex.repo.repo_items WHERE `ns0:header`.`ns0:identifier` IN (SELECT nid FROM repo_locs) GROUP BY 1
),
repo_fill AS (
  SELECT r.work_id,
    min(CASE WHEN lv.dates IS NOT NULL AND (b.dates IS NULL OR to_date(substr(lv.ds, 1, 10)) >= to_date(substr(b.ds, 1, 10)))
               THEN dc_date_fill(lv.dates)
             WHEN b.dates IS NOT NULL THEN dc_date_fill(b.dates) END) AS d
  FROM repo_locs r LEFT JOIN b ON b.nid = r.nid AND b.ep = r.ep LEFT JOIN lv ON lv.nid = r.nid
  GROUP BY r.work_id
),
dc_locs AS (
  SELECT t.work_id, lower(l.native_id) AS doi
  FROM targets t LATERAL VIEW explode(t.locations) x AS l WHERE l.provenance = 'datacite'
),
dc AS (
  SELECT lower(id) AS doi, max_by(attributes, attributes.updated) AS attributes
  FROM openalex.datacite.datacite_items WHERE lower(id) IN (SELECT doi FROM dc_locs) GROUP BY 1
),
dc_fill AS (
  SELECT dc_locs.work_id, min(CASE WHEN exists(coalesce(attributes.dates, array()),
                 x -> x.date RLIKE '^[0-9]{4}[^/]*/[0-9]{4}'
                      AND abs(int(regexp_extract(x.date, '/([0-9]{4})', 1)) - int(substr(x.date, 1, 4))) > 5)
     THEN NULL
ELSE array_min(filter(
  concat(
    transform(filter(coalesce(attributes.dates, array()), x -> lower(x.dateType) IN ('issued', 'available', 'copyrighted')),
              x -> CASE WHEN x.date RLIKE '^[0-9]{4}-[0-9]{2}-[0-9]{2}' THEN to_date(try_to_timestamp(substr(x.date, 1, 10), 'yyyy-MM-dd'))
                        WHEN x.date RLIKE '^[0-9]{4}-[0-9]{2}$' AND substr(x.date, 6, 2) BETWEEN '01' AND '12'
                          THEN make_date(int(substr(x.date, 1, 4)), int(substr(x.date, 6, 2)), 1)
                        WHEN x.date RLIKE '^[0-9]{4}' AND int(substr(x.date, 1, 4)) >= 1500
                          THEN make_date(int(substr(x.date, 1, 4)), 1, 1) END),
    array(CASE WHEN attributes.publicationYear BETWEEN 1500 AND year(current_date()) + 1
               THEN make_date(int(attributes.publicationYear), 1, 1) END)),
  y -> y IS NOT NULL AND year(y) BETWEEN 1500 AND 1899
       AND NOT (month(y) = 1 AND day(y) = 1 AND year(y) IN (1500, 1501, 1600, 1601, 1700, 1701, 1800, 1801))))
END) AS d
  FROM dc_locs JOIN dc USING (doi) GROUP BY dc_locs.work_id
),
filled AS (
  SELECT t.work_id, coalesce(dc_fill.d, repo_fill.d) AS fill_publication_date,
    CASE WHEN dc_fill.d IS NOT NULL THEN 'datacite' ELSE 'repo_dc_date' END AS fill_source,
    coalesce(t.src_id, t.src_ep, CASE WHEN dc_fill.d IS NOT NULL THEN regexp_extract(t.doi, '(10\.[0-9]+)', 1) END, 'unknown') AS src_key
  FROM targets t LEFT JOIN dc_fill USING (work_id) LEFT JOIN repo_fill USING (work_id)
  WHERE coalesce(dc_fill.d, repo_fill.d) IS NOT NULL
),
-- the gate: a year the record-reading resolver accepted (ResolvePublicationYears, prompt jev-v1, confidence >= 0.95).
-- The regex date above only supplies the month and day when its year is the resolver's year.
accepted AS (
  SELECT r.work_id,
    CASE WHEN year(f.fill_publication_date) = r.year THEN f.fill_publication_date ELSE make_date(r.year, 1, 1) END
      AS fill_publication_date,
    CASE WHEN year(f.fill_publication_date) = r.year THEN concat('jev-v1+', f.fill_source) ELSE 'jev-v1' END AS fill_source,
    q.src_key
  FROM openalex.works.publication_year_resolved r
  JOIN openalex.works.publication_year_queue q USING (work_id)
  LEFT JOIN filled f USING (work_id)
  WHERE r.prompt_version = 'jev-v1' AND r.year IS NOT NULL AND r.conf >= 0.95
)
SELECT work_id, fill_publication_date, fill_source, current_timestamp() AS built_at
FROM accepted
-- collections whose year is a placeholder (Jason's pre-1900 audit; scratch/analyze_audit.py, evidence/denylist_cells.json)
WHERE NOT ((src_key = 'https://openalex.org/S4306400126' AND year(fill_publication_date) = 1730) OR (src_key = 'https://openalex.org/S4306400359' AND year(fill_publication_date) = 1880) OR (src_key = 'https://openalex.org/S4306400518' AND year(fill_publication_date) = 1890) OR (src_key = 'https://openalex.org/S4306401134' AND year(fill_publication_date) = 1850) OR (src_key = 'https://openalex.org/S4306402217' AND year(fill_publication_date) = 1840) OR (src_key = 'https://openalex.org/S4306402217' AND year(fill_publication_date) = 1850) OR (src_key = 'https://openalex.org/S4306402611' AND year(fill_publication_date) = 1786) OR (src_key = 'https://openalex.org/S4306402611' AND year(fill_publication_date) = 1881) OR (src_key = 'https://openalex.org/S7407064294' AND year(fill_publication_date) = 1891));
