#!/usr/bin/env python3
"""Generate notebooks/awards/CreateOrUpdateAwards.sql, the one Awards job notebook (pipeline piece 1).

Edit only the inputs, then rerun this script and commit all three:
  notebooks/awards/sources.csv            one row per source, in run order:
      source         the provenance written to raw; also the prefix of the source's views and variables
      priority       raw priority, unchanged from the source's old notebook
      funder_ids     every funder the mapping may emit, F-prefixed, joined with |
      s3_path        a prefix ending in / (the newest *.parquet under it is read) or one .parquet object
      fetch_cadence  weekly | monthly | manual (a prefix) | frozen (one saved object that never changes)
      row_floor_pct  skip the source when the file maps to fewer rows than this percent of raw's slice (98 = default)
  notebooks/awards/sources/<source>.sql  the mapping: comment lines, then WITH ... awards_transformed AS (...),
      reading the view <source>_input. It ends at the closing parenthesis of awards_transformed.

Every source gets the same block: read the newest object, pin a baseline at the current raw version, compare
null-safely, guard (row floor, duplicate keys, invalid rows, no object), then one MERGE with no DELETE branch.
A frozen source whose object is older than raw's newest row for its slice reads, compares and merges nothing:
its result row says 'unchanged object'.

Usage: python3 scripts/gen_awards_sql.py           rewrite the notebook
       python3 scripts/gen_awards_sql.py --check   exit 1 if the committed notebook differs from the render (CI)
"""
