def fail(msg):
    raise SystemExit(f'gen_awards_sql: {msg}')


def load(awards=AWARDS):
    """sources.csv rows, checked, each with its mapping text."""
    with open(awards / 'sources.csv', newline='') as f:
        reader = csv.DictReader(f)
        if reader.fieldnames != COLUMNS:
            fail(f'sources.csv header must be {",".join(COLUMNS)}')
        rows = list(reader)
    seen = set()
    for n, r in enumerate(rows, start=2):
        where = f'sources.csv line {n}'
        if None in r or any(v is None or v != v.strip() for v in r.values()):
            fail(f'{where}: wrong field count or stray spaces')
        s = r['source']
        if not re.fullmatch(r'[a-z][a-z0-9_]*', s) or s in seen:
            fail(f'{where}: source {s!r} must be a new lower_snake name')
        seen.add(s)
        if not re.fullmatch(r'[1-9][0-9]*', r['priority']):
            fail(f'{where}: priority must be a positive integer')
        ids = r['funder_ids'].split('|')
        if not all(re.fullmatch(r'F[1-9][0-9]*', i) for i in ids) or len(set(ids)) != len(ids):
            fail(f'{where}: funder_ids must be distinct F<digits> joined with |')
        path, cadence = r['s3_path'], r['fetch_cadence']
        if not path.startswith(PREFIX) or not re.fullmatch(r'[A-Za-z0-9_./:-]+', path):
            fail(f'{where}: s3_path must be under {PREFIX}')
        if cadence in ('weekly', 'monthly') and not path.endswith('/'):
            fail(f'{where}: a {cadence} source reads a prefix (ends with /)')
        if cadence == 'frozen' and not path.endswith('.parquet'):
            fail(f'{where}: a frozen source reads one .parquet object')
        if cadence not in ('weekly', 'monthly', 'manual', 'frozen') or not path.endswith(('/', '.parquet')):
            fail(f'{where}: fetch_cadence or s3_path not recognised')
        if not re.fullmatch(r'[1-9][0-9]?|100', r['row_floor_pct']):
            fail(f'{where}: row_floor_pct must be 1-100')
        mapping_file = awards / 'sources' / f'{s}.sql'
        if not mapping_file.exists():
            fail(f'{where}: missing sources/{s}.sql')
        mapping = mapping_file.read_text().rstrip('\n')
        code = [l for l in mapping.splitlines() if not l.lstrip().startswith('--')]
        if any(';' in l for l in code) or '{{' in mapping:
            fail(f'sources/{s}.sql: no semicolons or {{{{ }}}} placeholders outside comment lines')
        if f'{s}_input' not in mapping or 'awards_transformed AS (' not in mapping or not mapping.endswith(')'):
            fail(f'sources/{s}.sql: must read {s}_input and end with the awards_transformed CTE')
        if not code or not re.match(r'WITH\s', code[0] + ' ') or re.search(rf'\b{s}_input\s+AS\s*\(', mapping, re.I):
            fail(f'sources/{s}.sql: must start with WITH (after comment lines) and must not define {s}_input itself')
        r['mapping'] = mapping
    extra = {p.stem for p in (awards / 'sources').glob('*.sql')} - seen
    if extra:
        fail(f'sources/ has mappings with no sources.csv row: {sorted(extra)}')
    return rows


def read_path(r):
    return r['s3_path'] + '*.parquet' if r['s3_path'].endswith('/') else r['s3_path']


def branch(r):
    """The source's comment lines, then its mapping spliced after its pinned input CTE."""
    lines = r['mapping'].splitlines()
    k = next(i for i, l in enumerate(lines) if not l.lstrip().startswith('--'))
    comments, code = lines[:k], '\n'.join(lines[k:])
    rest = re.sub(r'^WITH\s+', '', code, count=1)
    body = BRANCH.format(source=r['source'], priority=r['priority'], cadence=r['fetch_cadence'],
                         read_path=read_path(r), mapping_rest=rest)
    return '\n'.join(comments + [body]) if comments else body


def render(rows):
    source_rows = ',\n'.join(
        f" ({n}, '{r['source']}', {r['priority']}, {r['row_floor_pct']}, "
        f"array({', '.join(i[1:] + 'L' for i in r['funder_ids'].split('|'))}), '{r['fetch_cadence']}', {(n - 1) // CHUNK + 1})"
        for n, r in enumerate(rows, start=1))
    frozen = [r for r in rows if r['fetch_cadence'] == 'frozen']
    named = ['SELECT * FROM VALUES\n' + ',\n'.join(f" ('{r['source']}', '{r['s3_path']}')" for r in frozen)
             + '\nAS t(source, object)'] if frozen else []
    object_rows = '\nUNION ALL\n'.join(named + [OBJECT.format(source=r['source'], read_path=read_path(r))
                                                 for r in rows if r['fetch_cadence'] != 'frozen'])
    n = len(rows)
    chunks = (n + CHUNK - 1) // CHUNK
    views = [CHUNK_VIEW.format(chunk=c, chunks=chunks, first=(c - 1) * CHUNK + 1, last=min(c * CHUNK, n),
                               branches='\nUNION ALL\n'.join(branch(r) for r in rows[(c - 1) * CHUNK:c * CHUNK]))
             for c in range(1, chunks + 1)]
    candidates = ' UNION ALL '.join(f'SELECT * FROM awards_candidate_{c}' for c in range(1, chunks + 1))
    return (HEADER.format(source_rows=source_rows, object_rows=object_rows) + ''.join(views)
            + FOOTER.replace('{candidates}', candidates).replace('{count}', WORDS[n] if n < len(WORDS) else str(n)))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--check', action='store_true', help='exit 1 if the committed notebook is stale')
    args = ap.parse_args()
    rows = load()
    text = render(rows)
    target = AWARDS / 'CreateOrUpdateAwards.sql'
    if args.check:
        if target.read_text() != text:
            sys.exit('CreateOrUpdateAwards.sql is stale or hand-edited: run python3 scripts/gen_awards_sql.py and commit it')
        print(f'CreateOrUpdateAwards.sql is current ({len(rows)} sources)')
        return
    target.write_text(text)
    print(f'wrote {target.relative_to(AWARDS.parents[1])} ({len(rows)} sources)')


if __name__ == '__main__':
    main()
